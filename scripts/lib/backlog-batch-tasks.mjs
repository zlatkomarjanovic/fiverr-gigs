export function buildBatchTasks() {
  const tasks = [];
  for (let i = 80; i < 300; i++) {
    const category = cats[i % cats.length];
    const n = Math.floor(i / cats.length) + 1;
    const key = `${category}-batch-${n}`;
    const list = descriptions[category];
    const batchIndex = n - 6;
    const task = list[batchIndex] || `${category} improvement batch ${n}`;
    tasks.push({ category, key, task, scope: n <= 8 ? "XS" : "S" });
  }
  return tasks;
}

export const batchTaskKeys = buildBatchTasks().map((t) => t.key);
